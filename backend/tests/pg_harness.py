"""Postgres test harness (P14A.1): a throwaway database per test.

Offline tests run on SQLite, so everything that only Postgres does (the adapted
SQL, ``ON CONFLICT``, row locks, ``lock_timeout``, TEXT ``scraped_at`` ordering)
had no test. This module gives the ``pg`` tier its database:

* ``TEST_PG_ADMIN_DSN`` is the ONE input. It is never read from
  ``INVENTORY_DATABASE_URL``, ``DATABASE_URL`` or ``.env``, so a shell that is
  pointed at ``cars`` cannot point the tests at it.
* A TEMPLATE database is built once per session by the real migration chain
  (``migrate.main(['--apply'])``), so the tests run on the schema prod gets.
* Each test gets ``CREATE DATABASE ... TEMPLATE <tmpl> STRATEGY WAL_LOG`` and a
  ``DROP DATABASE ... WITH (FORCE)`` afterwards. ``FILE_COPY`` is never used: on
  the cluster that holds ``cars`` it forces cluster-wide checkpoints while the
  fleet writes.
* Safety (D-TC9): only a local server (unix socket, loopback, or the CI service
  alias), never a Railway host, never port 15432 (the mini -> MBP tunnel), only
  ``postgres``/``template1`` as the admin database, and only ``pytest_*`` names
  are ever created or dropped. ``cars`` and ``cars_cleanroom`` are refused by
  name at every entry point.

Rule for later pg test files: do not edit this file; keep helpers local to the
test file and file a harness follow-up (worktree conflicts).
"""

