JANITOR_MAX_AGE_S = 6 * 3600


class HarnessRefused(RuntimeError):
    """The admin DSN or a database name is not one the harness may touch."""


class PgUnavailable(RuntimeError):
    """The server cannot host the tier (no superuser, missing extension, too old)."""


