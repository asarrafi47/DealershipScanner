def _reset_value(kind: str, current: Any) -> Any:
    if kind == "false":
        return False
    if kind == "none":
        return None
    if kind == "zero":
        return 0.0
    raise ValueError(kind)


def reset_pg_process_caches() -> None:
    """Forget every per-process "this database is ready / the fleet looks like this" memo."""
    # The thread-local shared read connection (inventory_pg.borrow_read_connection)
    # would otherwise point at a dropped database.
    ipg = sys.modules.get("backend.db.inventory_pg")
    if ipg is not None:
        shared = getattr(ipg, "_shared_read", None)
        raw = getattr(shared, "raw", None)
        if raw is not None:
            try:
                raw.close()
            except Exception:
                pass
            shared.raw = None
    for mod_name, fn_name in _RESET_FUNCTIONS:
        fn = getattr(sys.modules.get(mod_name), fn_name, None)
        if callable(fn):
            fn()
    for mod_name, attr, kind in _FLAG_RESETS:
        module = sys.modules.get(mod_name)
        if module is None or not hasattr(module, attr):
            continue
        if kind == "clear":
            getattr(module, attr).clear()
        else:
            setattr(module, attr, _reset_value(kind, getattr(module, attr)))
    for mod_name, fn_name in _LRU_RESETS:
        clear = getattr(getattr(sys.modules.get(mod_name), fn_name, None), "cache_clear", None)
        if clear is not None:
            clear()


