def _backend_root() -> Path:
    return Path(__file__).resolve().parents[1]


def _module_name(rel: Path) -> str:
    parts = ["backend", *rel.with_suffix("").parts]
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def sweep_cache_flags(root: Path | None = None) -> dict[str, str]:
    """Every module-level cache/ready flag and inventory-reading ``lru_cache`` in ``backend``.

    Read from source (AST), so modules are not imported. Returns
    ``{"<module>.<name>": "flag" | "lru_cache"}``. Tests and this package's own
    code are skipped.
    """
    root = root or _backend_root()
    found: dict[str, str] = {}
    for path in sorted(root.rglob("*.py")):
        rel = path.relative_to(root)
        if rel.parts[0] == "tests" or "__pycache__" in rel.parts:
            continue
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except (SyntaxError, UnicodeDecodeError, OSError):
            continue
        mod = _module_name(rel)
        for node in tree.body:
            targets: list[ast.expr] = []
            if isinstance(node, ast.Assign):
                targets = list(node.targets)
            elif isinstance(node, (ast.AnnAssign, ast.AugAssign)):
                targets = [node.target]
            for t in targets:
                if isinstance(t, ast.Name) and t.id.startswith("_") and _FLAG_NAME_RE.search(t.id):
                    found[f"{mod}.{t.id}"] = "flag"
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                cached = any("lru_cache" in ast.unparse(d) or ast.unparse(d).endswith("cache") for d in node.decorator_list)
                if cached and any(h in ast.dump(node) for h in _DB_HINTS):
                    found[f"{mod}.{node.name}"] = "lru_cache"
    return found


def sweep_unaccounted(root: Path | None = None) -> list[str]:
    """Swept names that are neither reset by the harness nor reviewed as DB-independent."""
    reset = {f"{m}.{a}" for m, a, _ in _FLAG_RESETS}
    reset |= {f"{m}.{fn}" for m, fn in _LRU_RESETS}
    return sorted(n for n in sweep_cache_flags(root) if n not in reset and n not in _SWEEP_REVIEWED)


