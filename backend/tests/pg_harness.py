def admin_dsn() -> str | None:
    """The admin DSN from ``TEST_PG_ADMIN_DSN`` only; None when unset or blank."""
    return (os.environ.get(ADMIN_DSN_ENV) or "").strip() or None


def require_pg() -> bool:
    return (os.environ.get(REQUIRE_PG_ENV) or "").strip() == "1"


def _conninfo(dsn: str) -> dict[str, str]:
    from psycopg.conninfo import conninfo_to_dict

    return {k: str(v) for k, v in conninfo_to_dict(dsn).items() if v is not None}


def _in_ci() -> bool:
    return bool((os.environ.get("CI") or "").strip() or (os.environ.get("GITHUB_ACTIONS") or "").strip())


def assert_safe_admin_dsn(dsn: str) -> None:
    """Raise HarnessRefused unless *dsn* is a local server's admin database.

    libpq falls back to PGHOST / PGHOSTADDR / PGPORT / PGDATABASE when the DSN
    omits them, so those count as if written in the DSN.
    """
    if not dsn or not dsn.strip():
        raise HarnessRefused("empty admin DSN")
    try:
        info = _conninfo(dsn)
    except Exception as exc:
        raise HarnessRefused(f"unparseable admin DSN: {type(exc).__name__}") from None

    host_spec = info.get("host") if "host" in info else os.environ.get("PGHOST", "")
    for host in (host_spec or "").split(","):
        host = host.strip().lower()
        if any(host.endswith(sfx) or host == sfx.lstrip(".") for sfx in FORBIDDEN_HOST_SUFFIXES):
            raise HarnessRefused(f"admin host {host!r} is a Railway host; refused")
        if host in LOCAL_HOSTS or host.startswith("/"):
            continue
        if host in CI_SERVICE_ALIASES and _in_ci():
            continue
        raise HarnessRefused(
            f"admin server must be local (unix socket, loopback or the CI service alias); got host {host!r}"
        )
    addr = info.get("hostaddr") or os.environ.get("PGHOSTADDR", "")
    for a in (addr.split(",") if addr else ()):
        if a.strip() not in ("127.0.0.1", "::1"):
            raise HarnessRefused(f"admin server must be local; got hostaddr {a!r}")
    port_spec = info.get("port") or os.environ.get("PGPORT", "")
    if TUNNEL_PORT in [p.strip() for p in port_spec.split(",")]:
        raise HarnessRefused(f"port {TUNNEL_PORT} is the mini's tunnel to the inventory server; refused")
    dbname = info.get("dbname") or os.environ.get("PGDATABASE", "") or info.get("user", "")
    if dbname not in ADMIN_DBNAMES:
        raise HarnessRefused(
            f"admin dbname must be one of {sorted(ADMIN_DBNAMES)}, got {dbname!r} "
            "(the harness never connects to a data database)"
        )


def assert_scratch_name(name: str) -> None:
    """Only ``pytest_<epoch>_[tmpl_]<hex>`` names are created or dropped."""
    if name in PROTECTED_DBS:
        raise HarnessRefused(f"{name!r} is a protected database")
    if not _NAME_RE.match(name):
        raise HarnessRefused(f"scratch name {name!r} must match {_NAME_RE.pattern}")


def dsn_for(admin: str, dbname: str) -> str:
    """Same server and credentials, another database, as a libpq URL.

    URL form because the repo's inventory resolver accepts only ``postgresql://``.
    """
    from urllib.parse import quote, urlencode

    params = {k: v for k, v in sorted(_conninfo(admin).items()) if k != "dbname"}
    query = urlencode(params, quote_via=quote, safe="/")
    return f"postgresql:///{quote(dbname, safe='')}" + (f"?{query}" if query else "")


def new_name(kind: str = "db") -> str:
    suffix = secrets.token_hex(4)
    name = f"pytest_{int(time.time())}_{'tmpl_' if kind == 'tmpl' else ''}{suffix}"
    assert_scratch_name(name)
    return name


