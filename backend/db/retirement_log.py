"""Provenance and strikes for retirements (N9 P5B.3, P5B.4).

``listing_retirements`` (migrations/V032) gets one row per car a writer un-lists or deletes,
written in the writer's own transaction; ``listing_miss_strikes`` (V033) holds the first
miss of the two-strike policy. Both tables are created lazily here (``CREATE TABLE IF NOT
EXISTS``) so a database that is behind the migration chain, and the SQLite test schema,
behave the same; the DDL mirrors the migration files.

Everything takes a cursor or connection (anything with ``execute``) so a writer logs on
the connection that holds its UPDATE. Scanner writers call with ``strict=True``: a failed
provenance write raises, the transaction rolls back and the retirement does not happen.
Admin deletes call with ``strict=False``: the write sits in a savepoint and a failure is
logged, never blocks the delete.
"""
from __future__ import annotations

import json
import logging
import os
from datetime import datetime, timedelta, timezone
from typing import Any, Iterable, Sequence

from backend.db.inventory_pg import is_inventory_postgres

logger = logging.getLogger(__name__)

WRITERS = ("scanner_reconcile", "delta_scan", "disown", "pipeline_w2", "portal_sync", "admin_delete")

_CHUNK = 400

_PK = {
    True: "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    False: "id INTEGER PRIMARY KEY AUTOINCREMENT",
}
_CAR_ID = {True: "bigint", False: "INTEGER"}


def _ddl() -> list[str]:
    pg = is_inventory_postgres()
    return [
        f"""CREATE TABLE IF NOT EXISTS listing_retirements (
            {_PK[pg]},
            car_id {_CAR_ID[pg]} NOT NULL,
            vin TEXT,
            dealer_id TEXT,
            writer TEXT NOT NULL,
            reason TEXT,
            strikes INTEGER,
            evidence TEXT,
            created_at TEXT NOT NULL
        )""",
        "CREATE INDEX IF NOT EXISTS idx_listing_retirements_car ON listing_retirements (car_id)",
        "CREATE INDEX IF NOT EXISTS idx_listing_retirements_dealer ON listing_retirements (dealer_id, created_at)",
        f"""CREATE TABLE IF NOT EXISTS listing_miss_strikes (
            car_id {_CAR_ID[pg]} PRIMARY KEY,
            dealer_id TEXT NOT NULL,
            vin TEXT,
            strikes INTEGER NOT NULL DEFAULT 1,
            first_missed_at TEXT NOT NULL,
            last_missed_at TEXT NOT NULL,
            source TEXT
        )""",
        "CREATE INDEX IF NOT EXISTS idx_listing_miss_strikes_dealer ON listing_miss_strikes (dealer_id)",
    ]


def ensure_retirement_tables(cur: Any) -> None:
    """Create both tables when missing (idempotent; a no-op on a migrated database)."""
    for stmt in _ddl():
        cur.execute(stmt)


def retire_strikes() -> int:
    """``SCANNER_RETIRE_STRIKES``: misses it takes to retire a car. 2 (default, D-RC2) or 1."""
    raw = (os.environ.get("SCANNER_RETIRE_STRIKES") or "2").strip()
    try:
        return 1 if int(float(raw)) <= 1 else 2
    except ValueError:
        return 2


def strike_gap_hours() -> float:
    """``SCANNER_STRIKE_GAP_HOURS``: least hours between the first miss and the retiring one."""
    raw = (os.environ.get("SCANNER_STRIKE_GAP_HOURS") or "20").strip()
    try:
        return max(0.0, float(raw))
    except ValueError:
        return 20.0


def _now_iso() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def _parse(ts: Any) -> datetime | None:
    try:
        dt = datetime.fromisoformat(str(ts).strip().replace("Z", "+00:00"))
    except ValueError:
        return None
    return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)


class _Guard:
    """Savepoint around best-effort writes: a failure rolls back to it, never the outer txn."""

    def __init__(self, cur: Any, enabled: bool, *, quiet: bool = False):
        self.cur, self.enabled, self.quiet = cur, enabled, quiet

    def __enter__(self):
        if self.enabled:
            self.cur.execute("SAVEPOINT retirement_log")
        return self

    def __exit__(self, exc_type, exc, tb):
        if not self.enabled:
            return False
        if exc_type is None:
            self.cur.execute("RELEASE SAVEPOINT retirement_log")
            return False
        try:
            self.cur.execute("ROLLBACK TO SAVEPOINT retirement_log")
            self.cur.execute("RELEASE SAVEPOINT retirement_log")
        except Exception:  # noqa: BLE001
            pass
        if self.quiet:  # a read of a table the database has not got yet is the normal pre-migration case
            logger.debug("retirement_log: read skipped: %s", exc)
        else:
            logger.warning("retirement_log: write skipped", exc_info=(exc_type, exc, tb))
        return True


def record_retirements(
    cur: Any,
    rows: Iterable[Sequence[Any]],
    *,
    writer: str,
    reason: str = "",
    strikes: int | None = None,
    evidence: dict[str, Any] | None = None,
    strict: bool = True,
) -> int:
    """One ``listing_retirements`` row per ``(car_id, vin, dealer_id)`` in *rows*; returns the count.

    *evidence* is stored as JSON; a row may carry its own as a fourth element (a dict) that
    is merged over it. Call inside the transaction that holds the UPDATE/DELETE.
    """
    items = [tuple(r) for r in rows]
    if not items:
        return 0
    now = _now_iso()
    with _Guard(cur, not strict):
        ensure_retirement_tables(cur)
        for it in items:
            ev = dict(evidence or {})
            if len(it) > 3 and isinstance(it[3], dict):
                ev.update(it[3])
            cur.execute(
                "INSERT INTO listing_retirements (car_id, vin, dealer_id, writer, reason, strikes, evidence, created_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                (int(it[0]), it[1], it[2], writer, reason or None, strikes,
                 json.dumps(ev, sort_keys=True, default=str) if ev else None, now),
            )
        return len(items)
    return 0


def read_strikes(cur: Any, car_ids: Sequence[int]) -> dict[int, dict[str, Any]]:
    """``{car_id: {strikes, first_missed_at}}`` for the cars that hold a strike.

    Read only: a database without the table answers ``{}`` (nothing struck yet).
    """
    out: dict[int, dict[str, Any]] = {}
    ids = [int(i) for i in car_ids]
    if not ids:
        return out
    with _Guard(cur, True, quiet=True):
        for i in range(0, len(ids), _CHUNK):
            chunk = ids[i : i + _CHUNK]
            cur.execute(
                f"SELECT car_id, strikes, first_missed_at FROM listing_miss_strikes "
                f"WHERE car_id IN ({','.join('?' * len(chunk))})",
                tuple(chunk),
            )
            for r in cur.fetchall():
                out[int(r[0])] = {"strikes": int(r[1] or 1), "first_missed_at": r[2]}
    return out


def split_by_strikes(
    candidates: Sequence[int], strikes: dict[int, dict[str, Any]], now: datetime, *, needed: int, gap_hours: float,
) -> tuple[list[int], list[int], list[int]]:
    """Split the policy's retire ids into ``(retire, first_strike, waiting)``.

    ``needed`` 1 retires everything. With 2, a car with no strike gets its first; one whose
    first miss is at least *gap_hours* old retires; a younger one waits (same-day reruns
    never double-count).
    """
    if needed <= 1:
        return list(candidates), [], []
    retire: list[int] = []
    first: list[int] = []
    waiting: list[int] = []
    for cid in candidates:
        st = strikes.get(int(cid))
        if not st:
            first.append(cid)
            continue
        t0 = _parse(st.get("first_missed_at"))
        if t0 is not None and now - t0 >= timedelta(hours=gap_hours):
            retire.append(cid)
        else:
            waiting.append(cid)
    return retire, first, waiting


def record_strikes(cur: Any, rows: Iterable[Sequence[Any]], *, source: str = "") -> int:
    """Insert a first strike per ``(car_id, vin, dealer_id)``; existing strikes are left alone."""
    items = [tuple(r) for r in rows]
    if not items:
        return 0
    now = _now_iso()
    ensure_retirement_tables(cur)
    for car_id, vin, dealer_id, *_ in items:
        cur.execute(
            "INSERT INTO listing_miss_strikes (car_id, dealer_id, vin, strikes, first_missed_at, last_missed_at, source) "
            "VALUES (?, ?, ?, 1, ?, ?, ?) ON CONFLICT (car_id) DO NOTHING",
            (int(car_id), dealer_id or "", vin, now, now, source or None),
        )
    return len(items)


def clear_strikes(cur: Any, car_ids: Iterable[int]) -> None:
    """Drop the strikes of cars that were seen again or have just been retired."""
    ids = [int(i) for i in car_ids]
    for i in range(0, len(ids), _CHUNK):
        chunk = ids[i : i + _CHUNK]
        cur.execute(
            f"DELETE FROM listing_miss_strikes WHERE car_id IN ({','.join('?' * len(chunk))})", tuple(chunk)
        )
