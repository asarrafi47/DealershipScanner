"""The site stylesheet bundle: the global partials, concatenated in cascade order.

Every page used to emit 15 render-blocking ``<link rel=stylesheet>`` tags
(``frontend/templates/_head_css.html``). They are cached immutably behind ``?v=``,
so the cost is the first visit: 15 requests that each block first paint (6 at a
time over HTTP/1.1), and 15 separately compressed files where one brotli stream
over the whole ~285 KB compresses better than the parts.

Why a file built from the parts, and not a Flask route that concatenates:

* the file goes through the ordinary static view, so it gets the year-long
  ``immutable`` caching of every ``?v=`` URL and the precompressed ``.br``/``.gz``
  siblings that ``scripts/build_static_compressed.py`` writes (a route would have to
  compress in-process and re-implement conditional requests);
* ``build_static_compressed.py`` (run by Dockerfile.web) writes it first, so the
  image ships the bundle and its siblings;
* local dev and tests need no build step: the first template render of a process
  (every render under ``debug``) checks the bundle against the parts and rewrites it
  when it is missing or stale. When it cannot be written (read-only tree) the page
  falls back to the 15 separate links, which are the same bytes in the same order.

ORDER IS THE CASCADE. ``CSS_BUNDLE_PARTS`` is the order ``style.css``'s @import
chain had, which was the order of the rules before the split. Do not reorder.
14-vdp-uniform.css stays last on purpose: it normalises the car page's card
surfaces and heading scale over the per-section rules above it (17-instant-nav.css,
appended after it, touches none of those selectors).

The bundle's mtime is set to the newest part's mtime, so writing it never moves
``static_cache_ver`` (the newest mtime under the static root).
"""

from __future__ import annotations

import logging
import os
from pathlib import Path

_log = logging.getLogger(__name__)

CSS_BUNDLE_PARTS: tuple[str, ...] = (
    "css/00-base.css",
    "css/01-nav.css",
    "css/02-listings.css",
    "css/03-car-page.css",
    "css/04-dashboard.css",
    "css/05-car-tools.css",
    "css/06-dev.css",
    "css/07-dealer-admin.css",
    "css/08-marketing.css",
    "css/09-components.css",
    "css/10-pages.css",
    "css/11-overrides.css",
    "css/12-viewers.css",
    "css/13-landing-auth.css",
    "css/14-vdp-uniform.css",
    # Added 2026-11-20 (view transitions, click feedback, listings skeleton). Only its
    # own selectors and at-rules, so appending it changes no earlier cascade.
    "css/17-instant-nav.css",
)

CSS_BUNDLE_PATH = "css/site.bundle.css"

_HEADER = (
    "/* GENERATED by backend/web/css_bundle.py from the partials below, in cascade order.\n"
    "   Edit the partials, never this file (it is git-ignored and rebuilt). */\n"
)


def bundle_bytes(static_root) -> bytes:
    """The bundle's exact contents: a header, then each part behind a marker comment.

    Parts are joined byte for byte; the marker sits on its own line after a newline,
    so a part that ends without one (or inside a rule) cannot swallow the next."""
    root = Path(static_root)
    out = [_HEADER.encode()]
    for rel in CSS_BUNDLE_PARTS:
        out.append(f"\n/* ---- {rel} ---- */\n".encode())
        out.append((root / rel).read_bytes())
    out.append(b"\n")
    return b"".join(out)


def _parts_mtime(root: Path) -> float:
    return max(os.stat(root / rel).st_mtime for rel in CSS_BUNDLE_PARTS)


def ensure_bundle(static_root) -> bool:
    """Make ``CSS_BUNDLE_PATH`` equal to the concatenation of the parts.

    Returns True when the bundle on disk is current (already, or after a rewrite),
    False when it is not and could not be written: the caller then links the parts."""
    root = Path(static_root)
    target = root / CSS_BUNDLE_PATH
    try:
        want = bundle_bytes(root)
        mtime = _parts_mtime(root)
    except OSError:
        _log.warning("css bundle: a partial is unreadable; linking the parts", exc_info=True)
        return False
    try:
        if target.read_bytes() == want:
            st = target.stat()
            if st.st_mtime != mtime:
                os.utime(target, (mtime, mtime))
            return True
    except OSError:
        pass
    tmp = target.with_name(f"{target.name}.{os.getpid()}.tmp")
    try:
        tmp.write_bytes(want)
        os.utime(tmp, (mtime, mtime))
        os.replace(tmp, target)
    except OSError:
        _log.warning("css bundle: could not write %s; linking the parts", target, exc_info=True)
        try:
            tmp.unlink()
        except OSError:
            pass
        return False
    return True


_memo: bool | None = None


def css_bundle_ready() -> bool:
    """Whether templates should link the bundle (True) or the parts (False).

    Checked once per process (gunicorn preloads the app); under ``debug`` on every
    call, so an edited partial shows up on the next request as it always has."""
    global _memo
    from flask import current_app

    if current_app.debug or _memo is None:
        _memo = ensure_bundle(current_app.static_folder)
    return _memo


def reset_memo() -> None:
    global _memo
    _memo = None
