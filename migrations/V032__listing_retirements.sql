-- V032__listing_retirements.sql
--
-- N9 P5B.3 (D-RC7): per-VIN provenance for every retirement. A car leaves the active set
-- (listing_active = 0, or a hard delete from the admin screens) through exactly one writer,
-- and that writer leaves one row here in the same transaction: which car and VIN, which
-- dealer, which writer (scanner_reconcile, delta_scan, disown, pipeline_w2, portal_sync,
-- admin_delete), why, how many strikes it took, and the evidence the policy had.
-- The count of rows a writer wrote equals that writer's UPDATE rowcount, so an inactive
-- delta in `cars` can always be traced:
--
--   SELECT writer, count(*) FROM listing_retirements
--    WHERE created_at >= '2026-10-01' GROUP BY 1;
--
-- No foreign key to cars: the admin delete paths remove the car row and keep the proof.
-- The code also creates this table lazily (CREATE TABLE IF NOT EXISTS) on a database that
-- is behind the chain; backend/db/retirement_log.py is the runtime copy.
--
-- (The plan assigned V028; the integration head renumbered its own drafts to V028-V031,
-- so the next free number is V032.)

CREATE TABLE IF NOT EXISTS public.listing_retirements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id bigint NOT NULL,
    vin text,
    dealer_id text,
    writer text NOT NULL,
    reason text,
    strikes integer,
    evidence text,
    created_at text NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_listing_retirements_car
    ON public.listing_retirements (car_id);
CREATE INDEX IF NOT EXISTS idx_listing_retirements_dealer
    ON public.listing_retirements (dealer_id, created_at);
